#!/usr/bin/env node
/**
 * build_paper.js
 * ==============
 * Assembles the submission paper from the section documents.
 *
 * Why generate instead of hand-maintain: the paper and the docs/ sections would
 * otherwise drift apart the moment one is edited. This script makes docs/ the
 * single source of truth and the paper a build artefact.
 *
 * It also demotes each section document's headings by one level so that
 * "# 3. Methodology" becomes "## 3. Methodology" under the paper's own H1,
 * and rewrites intra-repo relative links so they still resolve from paper/.
 *
 * Usage:
 *     node tools/build_paper.js
 *     node tools/build_paper.js --check     # report drift without writing
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const PAPER_DIR = path.join(ROOT, "paper");
const DOCS_DIR = path.join(ROOT, "docs");

const FRONT_MATTER = path.join(PAPER_DIR, "front_matter.md");
const OUT_MD = path.join(PAPER_DIR, "CSE432_Bangla_Sentiment_BERT_Paper.md");

// Section order for the submission paper.
const SECTIONS = [
  "01_introduction.md",
  "02_literature_review.md",
  "03_methodology.md",
  "04_analysis.md",
  "05_conclusion.md",
];

const GENERATED = path.join(DOCS_DIR, "generated", "prior_work.md");

/**
 * Demote headings by `levels`, but never touch fenced code blocks — a '#'
 * inside a Python comment or a shell snippet is not a heading.
 */
function demoteHeadings(text, levels = 1) {
  const lines = text.split("\n");
  let inFence = false;
  return lines
    .map((line) => {
      if (/^\s*(```|~~~)/.test(line)) {
        inFence = !inFence;
        return line;
      }
      if (inFence) return line;
      const m = line.match(/^(#{1,6})(\s)/);
      if (!m) return line;
      return "#".repeat(Math.min(6, m[1].length + levels)) + line.slice(m[1].length);
    })
    .join("\n");
}

/**
 * Fix links that were written relative to docs/ but now live in paper/.
 *   [x](references.bib)      -> [x](../docs/references.bib)
 *   [x](generated/y.md)      -> [x](../docs/generated/y.md)
 * Absolute and external links are left alone.
 */
function rewriteLinks(text) {
  return text.replace(/\]\((?!https?:|#|mailto:|\.\.\/|\/)([^)\s]+)\)/g, (m, p1) => {
    if (/^[a-z]+:/i.test(p1)) return m;         // any other scheme
    return `](../docs/${p1})`;
  });
}

/** Strip the per-file H1 and the leading rule, since the paper supplies its own. */
function stripTitle(text) {
  const lines = text.split("\n");
  let i = 0;
  while (i < lines.length && lines[i].trim() === "") i++;
  if (i < lines.length && /^#\s/.test(lines[i])) {
    lines.splice(i, 1);
    i++;
    // drop an immediately following horizontal rule
    while (i < lines.length && lines[i].trim() === "") i++;
    if (i < lines.length && /^---\s*$/.test(lines[i])) lines.splice(i, 1);
  }
  return lines.join("\n");
}

function buildReferencesSection() {
  const bibPath = path.join(DOCS_DIR, "references.bib");
  if (!fs.existsSync(bibPath)) {
    return "> ⚠️ `docs/references.bib` not found.\n";
  }
  const bib = fs.readFileSync(bibPath, "utf8");
  const entries = bib.split(/(?=^@)/m).filter((e) => e.trim().startsWith("@"));
  const keys = entries.map((e) => {
    const m = e.match(/^@\w+\{([^,]+),/);
    return m ? m[1].trim() : "(unknown)";
  });

  let out = `## 6. References\n\n`;
  out += `${entries.length} entries, verified during this project. `;
  out += `Full BibTeX is in [\`docs/references.bib\`](../docs/references.bib).\n\n`;
  out += `| # | Citation key |\n|---|---|\n`;
  keys.forEach((k, i) => {
    out += `| ${i + 1} | \`${k}\` |\n`;
  });
  out += `\n---\n\n`;
  out += `### BibTeX source\n\n\`\`\`bibtex\n${bib.trim()}\n\`\`\`\n`;
  return out;
}

function main() {
  const checkOnly = process.argv.includes("--check");

  if (!fs.existsSync(FRONT_MATTER)) {
    console.error(`missing ${FRONT_MATTER}`);
    process.exit(1);
  }

  const parts = [];
  parts.push(fs.readFileSync(FRONT_MATTER, "utf8").trim());

  const missing = [];
  for (const sec of SECTIONS) {
    const p = path.join(DOCS_DIR, sec);
    if (!fs.existsSync(p)) {
      missing.push(sec);
      continue;
    }
    let body = fs.readFileSync(p, "utf8");
    body = stripTitle(body);
    body = demoteHeadings(body, 1);
    body = rewriteLinks(body);
    parts.push(`\n\n---\n\n${body.trim()}`);
  }

  if (missing.length) {
    console.error(`missing section files: ${missing.join(", ")}`);
    process.exit(1);
  }

  // Include the auto-generated literature tables if they exist.
  if (fs.existsSync(GENERATED)) {
    let gen = fs.readFileSync(GENERATED, "utf8");
    gen = demoteHeadings(gen, 2);
    parts.push(`\n\n---\n\n## Appendix A — Prior Work Filtered from \`bangla-nlp-catalog\`\n\n` +
               `Generated by \`src/catalog_to_lr.py\`. Regenerate before submission.\n\n` +
               gen.trim());
  } else {
    parts.push(`\n\n---\n\n## Appendix A — Prior Work Filtered from \`bangla-nlp-catalog\`\n\n` +
      `> ⚠️ Not yet generated. Run \`python src/catalog_to_lr.py --top 40\` after\n` +
      `> downloading the catalog (Notebook 01 §5.4), then rebuild this paper.\n` +
      `>\n` +
      `> The output will appear here as task-grouped tables of sentiment-related\n` +
      `> Bangla NLP resources.\n`);
  }

  parts.push(`\n\n---\n\n${buildReferencesSection()}`);

  parts.push(`\n\n---\n\n## Appendix B — Repository Manifest\n\n` +
    `| Path | Contents |\n|---|---|\n` +
    `| \`README.md\` | Colab buttons, dataset roles, contributor table, local folder location |\n` +
    `| \`docs/01_introduction.md\` | Section 1 — problem, motivation, objectives, contributions |\n` +
    `| \`docs/02_literature_review.md\` | Section 2 — prior work, research gap, positioning |\n` +
    `| \`docs/03_methodology.md\` | Section 3 — pipeline, models, training and evaluation protocol |\n` +
    `| \`docs/04_analysis.md\` | Section 4 — result slots, slice analyses, threats to validity |\n` +
    `| \`docs/05_conclusion.md\` | Section 5 — findings, limitations, future work |\n` +
    `| \`docs/references.bib\` | BibTeX, verified sources only |\n` +
    `| \`docs/generated/prior_work.md\` | Auto-generated literature tables (Appendix A) |\n` +
    `| \`notebooks/01_data_preprocessing.ipynb\` | Preprocessing, Colab-runnable |\n` +
    `| \`notebooks/02_bert_finetuning.ipynb\` | BERT fine-tuning, Colab-runnable, T4 GPU |\n` +
    `| \`notebooks/03_evaluation_and_analysis.ipynb\` | Evaluation and slices, Colab-runnable |\n` +
    `| \`src/config.py\` | Paths, dataset and model registry, label scheme, hyperparameters |\n` +
    `| \`src/download_datasets.py\` | Kaggle + Hugging Face fetchers with graceful degradation |\n` +
    `| \`src/preprocess.py\` | Stages B–I: normalisation, negation scope, labels, splits |\n` +
    `| \`src/catalog_to_lr.py\` | Catalog → literature-review table generator |\n` +
    `| \`src/train.py\` | Fine-tuning loop: class weights, discriminative LR, early stopping |\n` +
    `| \`src/evaluate.py\` | Metrics, figures, slice analyses, TF-IDF baseline |\n` +
    `| \`dataset/README.md\` | Regeneration instructions, output schemas |\n` +
    `| \`dataset/dataset_card.md\` | Provenance, licences, biases, ethics |\n` +
    `| \`tools/build_notebooks.js\` | Generates the three \`.ipynb\` files from cell sources |\n` +
    `| \`tools/build_paper.js\` | This script |\n` +
    `| \`tools/notebooks/*.cells.md\` | Editable cell sources for the notebooks |\n` +
    `| \`requirements.txt\` | Pinned dependency lower bounds |\n` +
    `| \`LICENSE\` | MIT for code; datasets remain under their original licences |\n\n` +
    `### Local folder location\n\n` +
    `This repository is located on the local PC at:\n\n` +
    `\`\`\`\nD:\\Documents\\qwen-agent\\lUinoenfmc\\default\\Developing-a-Bangla-Sentiment-Analysis-System-Using-Fine-Tuned-BERT-Models\n\`\`\`\n`);

  const doc = parts.join("\n") + "\n";

  if (checkOnly) {
    const words = doc.split(/\s+/).length;
    console.log(`[check] paper would be ${words.toLocaleString()} words, ` +
                `${doc.split("\n").length.toLocaleString()} lines`);
    console.log(`[check] sections found: ${SECTIONS.length}/${SECTIONS.length}`);
    return;
  }

  fs.mkdirSync(PAPER_DIR, { recursive: true });
  fs.writeFileSync(OUT_MD, doc, "utf8");

  // Keep the GitHub Pages copy in sync. This is served to the world from the
  // gh-pages branch via docs/assets/, so if it drifts from paper/ the live site
  // silently shows stale (or contradictory) numbers. That exact drift is what
  // produced the published 0.5768 vs. measured 0.6228 ablation conflict, so the
  // two copies are now written from the same buffer in one step.
  const PAGES_MD = path.join(DOCS_DIR, "assets", "CSE432_Bangla_Sentiment_BERT_Paper.md");
  fs.mkdirSync(path.dirname(PAGES_MD), { recursive: true });
  fs.writeFileSync(PAGES_MD, doc, "utf8");

  const words = doc.split(/\s+/).length;
  console.log(`[write] ${path.relative(ROOT, OUT_MD)}`);
  console.log(`[write] ${path.relative(ROOT, PAGES_MD)}  (GitHub Pages copy, kept in sync)`);
  console.log(`        ${words.toLocaleString()} words, ` +
              `${doc.split("\n").length.toLocaleString()} lines, ` +
              `${(doc.length / 1024).toFixed(1)} KB`);
}

main();
