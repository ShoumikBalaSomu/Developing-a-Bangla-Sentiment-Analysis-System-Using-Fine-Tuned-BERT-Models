"""
catalog_to_lr.py
================
Turns the `kishormorol/bangla-nlp-catalog` dataset into the structured
prior-work tables used in docs/02_literature_review.md.

The catalog is machine-readable: 813 papers, 63 datasets, 20 models and 9 tools
across 26 tasks, each tagged by task. Filtering it for sentiment-analysis work
gives a reproducible, date-stamped survey of Bangla opinion-mining literature
instead of a hand-picked (and therefore cherry-pickable) reference list.

Output
------
  dataset/preprocessed/literature_review_table.csv   full filtered table
  docs/generated/prior_work.md                       Markdown tables, ready to
                                                     paste into the report

Usage:
    python src/catalog_to_lr.py
    python src/catalog_to_lr.py --keyword "hate|offensive"   # different task
    python src/catalog_to_lr.py --top 40

CSE432 - Natural Language Processing
Authors: 232-15-657 Shoumik Bala Somu | 232-15-644 Raisha Khan Raka
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from config import ARTIFACTS, PREPROC_DIR, RAW_DIR, ROOT, banner, resolve_dataset_dir  # noqa: E402
from config import DATASETS  # noqa: E402

DEFAULT_KEYWORD = r"sentiment|opinion|emotion|affect|review"
GENERATED_DIR = ROOT / "docs" / "generated"

# Candidate column names. Different catalog revisions name these differently,
# so every accessor tries a list rather than assuming one schema.
TITLE_COLS = ["title", "name", "paper", "paper_title", "id", "resource"]
ABSTRACT_COLS = ["abstract", "summary", "description", "desc", "abstract_text"]
YEAR_COLS = ["year", "published", "date", "publication_year"]
TYPE_COLS = ["type", "kind", "category", "resource_type"]
TASK_COLS = ["task", "tasks", "task_name"]
VENUE_COLS = ["venue", "journal", "conference", "source"]
URL_COLS = ["url", "link", "doi", "href"]


def find_col(df: pd.DataFrame, candidates: list[str]) -> str | None:
    norm = {c.strip().lower(): c for c in df.columns}
    for cand in candidates:
        if cand in norm:
            return norm[cand]
    for cand in candidates:                      # substring fallback
        for low, orig in norm.items():
            if cand in low:
                return orig
    return None


def load_catalog() -> pd.DataFrame | None:
    """Try the registry dir, then the Kaggle mount, then any CSV in RAW_DIR."""
    candidates = [
        RAW_DIR / "bangla_nlp_catalog",
        resolve_dataset_dir(DATASETS["bangla_nlp_catalog"]["kaggle"]),
    ]
    for root in candidates:
        if not root.exists():
            continue
        for path in sorted(root.rglob("*.csv")):
            try:
                df = pd.read_csv(path)
            except Exception as exc:  # noqa: BLE001
                print(f"  [catalog] unreadable {path.name}: {str(exc)[:120]}")
                continue
            if df.empty:
                continue
            print(f"  [catalog] loaded {path.name}: {len(df):,} rows x {df.shape[1]} cols")
            print(f"  [catalog] columns: {list(df.columns)}")
            return df
    print("  [catalog] NOT FOUND. Run src/download_datasets.py --only bangla_nlp_catalog first.")
    return None


def matches(df: pd.DataFrame, pattern: str) -> pd.Series:
    """True where the regex hits ANY object column of the row."""
    rx = re.compile(pattern, re.I)
    mask = pd.Series(False, index=df.index)
    for col in df.columns:
        if df[col].dtype == object:
            mask |= df[col].astype(str).str.contains(rx, na=False)
    return mask


def build_markdown(df: pd.DataFrame, keyword: str, top: int) -> str:
    """Render Markdown tables grouped by resource type, newest first."""
    title_c = find_col(df, TITLE_COLS)
    year_c = find_col(df, YEAR_COLS)
    type_c = find_col(df, TYPE_COLS)
    task_c = find_col(df, TASK_COLS)
    venue_c = find_col(df, VENUE_COLS)
    url_c = find_col(df, URL_COLS)

    if title_c is None:
        return ("<!-- catalog_to_lr.py: no title-like column found in the catalog.\n"
                f"     columns were: {list(df.columns)}\n"
                "     Regenerate after inspecting the schema. -->\n")

    work = df.copy()
    if year_c:
        work["__year"] = pd.to_numeric(work[year_c], errors="coerce")
        work = work.sort_values("__year", ascending=False)
    group_col = work[type_c] if type_c else pd.Series("all", index=work.index)

    lines = [
        "<!-- AUTO-GENERATED by src/catalog_to_lr.py. Do not edit by hand. -->",
        f"<!-- keyword filter: {keyword} -->",
        f"<!-- matched entries: {len(work):,} -->",
        "",
        f"## Prior work filtered from `bangla-nlp-catalog` ({len(work):,} matched entries)",
        "",
    ]

    shown = 0
    for grp, sub in work.groupby(group_col, dropna=False):
        if shown >= top:
            break
        lines.append(f"### {str(grp).title()} ({len(sub):,})")
        lines.append("")
        head = ["Title", "Year"] + (["Task"] if task_c else []) + \
               (["Venue"] if venue_c else []) + ["Link"]
        lines.append("| " + " | ".join(head) + " |")
        lines.append("|" + "|".join(["---"] * len(head)) + "|")
        for _, r in sub.head(max(5, top // 4)).iterrows():
            title = str(r[title_c]).replace("|", "\\|")[:110]
            year = str(int(r["__year"])) if year_c and pd.notna(r.get("__year")) else ""
            task = str(r[task_c]).replace("|", "/")[:40] if task_c else ""
            venue = str(r[venue_c]).replace("|", "\\|")[:40] if venue_c else ""
            link = str(r[url_c]) if url_c and pd.notna(r.get(url_c)) else ""
            link = f"[link]({link})" if link.startswith("http") else ""
            cells = [title, year] + ([task] if task_c else []) + \
                    ([venue] if venue_c else []) + [link]
            lines.append("| " + " | ".join(cells) + " |")
            shown += 1
        lines.append("")

    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--keyword", default=DEFAULT_KEYWORD,
                    help="regex matched against every text column")
    ap.add_argument("--top", type=int, default=60, help="max entries to render")
    ap.add_argument("--out", default=None, help="Markdown output path")
    a = ap.parse_args()

    print(banner("bangla-nlp-catalog -> literature review"))
    df = load_catalog()
    if df is None:
        return 1

    hits = df[matches(df, a.keyword)].copy()
    print(f"  matched {len(hits):,} / {len(df):,} entries for /{a.keyword}/")
    if hits.empty:
        print("  [!] no matches - try a broader --keyword")
        return 1

    hits.to_csv(ARTIFACTS["lr_table"], index=False)
    print(f"  wrote {ARTIFACTS['lr_table']}")

    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    out = Path(a.out) if a.out else GENERATED_DIR / "prior_work.md"
    out.write_text(build_markdown(hits, a.keyword, a.top), encoding="utf-8")
    print(f"  wrote {out}")

    # Task-frequency summary: useful for the "state of the field" paragraph.
    task_c = find_col(hits, TASK_COLS)
    if task_c:
        freq = hits[task_c].astype(str).str.strip().value_counts().head(15)
        print(banner("Top matched tasks"))
        print(freq.to_string())
        freq.to_csv(PREPROC_DIR / "lr_task_frequency.csv")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
